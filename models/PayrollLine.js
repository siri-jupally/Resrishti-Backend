/*
  PayrollLine — what one person is paid for one month, and how it was arrived at.

  Every input is snapshotted, not referenced: the rate used, the day counts, the
  policy that decided which non-working days were paid. A line recomputed a year
  later from live data would give a different answer, because rates change and
  policies change — and the question a payslip has to answer is "what did we pay
  you in March", not "what would March cost today".

  This is the same reason certificates snapshot their line items.
*/
const mongoose = require("mongoose");

const payrollLineSchema = new mongoose.Schema(
    {
        run: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "PayrollRun",
            required: true,
            index: true,
        },
        month: { type: String, required: true, index: true },

        personType: { type: String, enum: ["Employee", "Manager"], required: true },
        personId: { type: mongoose.Schema.Types.ObjectId, required: true },
        // Denormalised so a payslip stays readable after somebody leaves.
        personName: String,
        personEmail: String,
        department: String,
        jobRole: String,

        // ---- what it was worked out from ----------------------------------
        payModel: { type: String, enum: ["monthly", "daily"], required: true },
        employmentType: String,
        rateAmount: Number,
        rateEffectiveFrom: String,
        perDayRate: Number,
        paidDayPolicyName: String,

        // ---- the month, day by day ----------------------------------------
        daysOnPayroll: Number,
        days: {
            worked: Number,
            halfDays: Number,
            leavePaid: Number,
            leaveUnpaid: Number,
            weeklyOffs: Number,
            holidays: Number,
            absent: Number,
            unapproved: Number,
            overtimeDays: Number,
            _id: false,
        },
        lopDays: Number,
        payableDays: Number,

        // ---- the money -----------------------------------------------------
        basePay: Number,
        overtimeDays: Number,
        overtimePay: Number,
        gross: Number,
        deductions: { type: Number, default: 0 },
        adjustments: { type: Number, default: 0 },
        net: Number,

        // Manual changes made during review. Capped and categorised rather than
        // free-form, so "other" cannot become a habit.
        adjustmentEntries: [
            {
                category: String,
                amount: Number,
                reason: String,
                at: { type: Date, default: Date.now },
                byName: String,
                _id: false,
            },
        ],

        // Anything the engine could not answer confidently about this person.
        exceptions: [
            {
                code: String,
                message: String,
                _id: false,
            },
        ],

        // Net against the same person last month, for the variance flag.
        previousNet: Number,
        variancePercent: Number,

        // The rendered payslip. Held here rather than in a collection of its
        // own: a payslip is this line, printed, and two records would give the
        // same figure two places to live.
        payslip: {
            number: String,
            key: String,
            bucket: String,
            generatedAt: Date,
            // Until this is set the payslip is not the person's to see.
            releasedAt: Date,
            _id: false,
        },

        // Whether this person's money actually left the building.
        //
        // This is the "payment level" the five-status rule points at: a failed
        // or part-made payment is a fact about one person, not a state of the
        // month, so it lives here and the run stays `approved` until every line
        // is settled. `attempts` keeps the failures after a retry succeeds —
        // without it, a payment that bounced twice and then worked looks like
        // it always worked.
        payment: {
            status: {
                type: String,
                enum: ["pending", "paid", "failed"],
                default: "pending",
            },
            // Bank reference / UTR for a payment that went out, as typed in
            // from the bank's response. Not generated by us.
            reference: { type: String, trim: true },
            amount: Number,
            paidAt: Date,
            paidBy: {
                userType: String,
                userId: mongoose.Schema.Types.ObjectId,
                name: String,
                _id: false,
            },
            failureReason: { type: String, trim: true },
            // Bank details as they stood when the payment was recorded. The
            // employee owns their account and can change it, so a payslip or a
            // query months later must show where the money actually went.
            bankSnapshot: {
                accountNumberLast4: String,
                ifsc: String,
                bankName: String,
                _id: false,
            },
            attempts: [
                {
                    status: { type: String, enum: ["paid", "failed"] },
                    reference: String,
                    failureReason: String,
                    at: { type: Date, default: Date.now },
                    byName: String,
                    _id: false,
                },
            ],
            _id: false,
        },
    },
    { timestamps: true }
);

payrollLineSchema.index({ run: 1, personType: 1, personId: 1 }, { unique: true });
payrollLineSchema.index({ month: 1, personId: 1 });

module.exports = mongoose.model("PayrollLine", payrollLineSchema);
